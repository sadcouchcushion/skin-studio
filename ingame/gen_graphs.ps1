function Flag-Check([string]$slot, $execFrom, [string]$execPin, [int]$x, [int]$y) {
    # DoesSaveGameExist(slot) -> Branch -> DeleteGameInSlot(slot); returns the delete node
    $ds = Call $GS 'DoesSaveGameExist' $x $y; Def $ds 'SlotName' 'string' $slot; Def $ds 'UserIndex' 'int' '0'
    Wire $execFrom $execPin $ds 'execute'
    $br = Branch ($x + 260) $y; Wire $ds 'then' $br 'execute'; Wire $ds 'ReturnValue' $br 'Condition'
    $dg = Call $GS 'DeleteGameInSlot' ($x + 460) $y; Def $dg 'SlotName' 'string' $slot; Def $dg 'UserIndex' 'int' '0'
    Wire $br 'then' $dg 'execute'
    $dg
}
# SendCmd's nodes written out in place, for level-1 events that cannot CALL
# SendCmd (it is pasted in the same block, so the call would lose its exec
# wires - see the header). $cmdParts go after "SLC_<ms>_", as for Concat-Chain.
function Inline-Send($execFrom, [string]$execPin, [object[]]$cmdParts, [int]$x, [int]$y) {
    $rt = Call $GS 'GetRealTimeSeconds' $x ($y + 160)
    $mu = Call $KM 'Multiply_DoubleDouble' ($x + 200) ($y + 160); Wire $rt 'ReturnValue' $mu 'A'; Def $mu 'B' 'real' '1000.000000'
    $ro = Call $KM 'Round' ($x + 400) ($y + 160); Wire $mu 'ReturnValue' $ro 'A'
    $mstr = Call $KSt 'Conv_IntToString' ($x + 600) ($y + 160); Wire $ro 'ReturnValue' $mstr 'InInt'
    $nm = Concat-Chain (@('SLC_', @($mstr, 'ReturnValue'), '_') + $cmdParts) ($x + 200) ($y + 280)
    $ld = Call $GS 'LoadGameFromSlot' ($x + 250) $y; Def $ld 'SlotName' 'string' 'HighlightSettings'; Def $ld 'UserIndex' 'int' '0'
    $sv = Call $GS 'SaveGameToSlot' ($x + 500) $y; Def $sv 'UserIndex' 'int' '0'
    Wire $execFrom $execPin $ld 'execute'; Wire $ld 'then' $sv 'execute'
    Wire $ld 'ReturnValue' $sv 'SaveGameObject'; Wire $nm 'ReturnValue' $sv 'SlotName'
    $sv
}
function Send-Literal($execFrom, [string]$execPin, [string]$cmd, [int]$x, [int]$y) {
