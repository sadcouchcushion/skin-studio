# gen_graphs.ps1 - writes the Blueprint graphs of the in-game editor as
# clipboard T3D, ready to paste into the UE 5.3 editor (D:\SkinLiveUE).
#
#   .\gen_graphs.ps1            -> D:\SkinLiveUE\paste\editor_1..4.txt, bootstrap.txt
#
# ---- why FOUR pastes for the editor widget -----------------------------------
# A pasted call to a custom event that is not compiled yet cannot find its
# function, and UE keeps orphaned DATA pins on reconstruct but never EXEC pins
# (K2Node.cpp: ESaveOrphanPinMode::SaveAllButExec) - the call would arrive with
# its exec wires cut. So the events go in by dependency level, compiling
# between pastes:
#   1  SendCmd, TrySwap, Splash             (call nothing of ours)
#   2  SendMouse, Walk, Close, MountLive    (call level 1)
#   3  Open, ReloadAll, AutoStart           (call levels 1-2)
#   4  Toggle, Tick, mouse, wheel
# The bootstrap is pasted last, once WBP_SkinLiveEditor_C is compiled. Its
# AutoTick timer (once a second) announces each hero spawned (-> AutoStart)
# and presses Project Galacta's F7 when Skin Studio asks (SkinLiveGalToggle).
#
# ---- what the format relies on (UE 5.3 source) -------------------------------
# Paste calls ReconstructNode on every node (EdGraphUtilities.cpp), which
# rebuilds pins from the real function signature and re-wires old pins by NAME
# and DIRECTION only (K2Node.cpp DoPinsMatchForReconstruction). So a pin here
# needs the right name; its type matters only when it carries a default. A
# default survives only if it differs from AutogeneratedDefaultValue, so that
# is always written empty. For Each loops carry ResolvedWildcardType, without
# which the macro never learns its element type (the old paste failure).
# -Hosted: the bootstrap for the merged !!SkinStudio mod, which creates this
# bootstrap itself and owns F8 (its colour panel's Studio button opens ours),
# so no F8 here. F6, AutoTick, the Galacta host and the splash all stay.
param([string]$Out = 'D:\SkinLiveUE\paste', [switch]$Hosted)
